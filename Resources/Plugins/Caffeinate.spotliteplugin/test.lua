-- This feature's checks live beside its implementation, independent of Swift.
return function(plugin)
    local s = require("spotlite")
    assert(not s.power.get({handle="display"}), "test requires an inactive initial lease")
    local function search(query) return plugin.search({query=query or ""}) end
    assert(#search().items == 4)
    assert(#search("tgc").items == 1, "fuzzy filtering")
    assert(#search("nothing matches").items == 0)
    search()
    plugin.action({action={id="toggle"},silent=true})
    assert(search().items[1].state == true)
    assert(s.power.get({handle="display"}))
    assert(s.status.get({id="indicator"}).tooltip:find("active in Spotlite",1,true))
    plugin.event({type="status.action",action="off",silent=true})
    assert(search().items[1].state == false)
    plugin.action({action={id="duration",data={seconds=0.05}},silent=true})
    s.timers.sleep({seconds=0.12})
    assert(not s.power.get({handle="display"}), "duration expiry")
    plugin.action({action={id="duration",data={seconds=60}},silent=true})
    plugin.action({action={id="toggle"},silent=true})
    assert(not s.power.get({handle="display"}), "duration cancellation")
    s.background(function() s.process.run({executable="/usr/bin/caffeinate",arguments={"-d","-t","1"}}) end)
    s.timers.sleep({seconds=0.2})
    plugin.event({type="status.open"})
    assert(search().items[1].subtitle == "Also active in another app", "external display assertion")
    assert(s.status.get({id="indicator"}).tooltip:find("another app",1,true))
    plugin.action({action={id="toggle"},silent=true})
    plugin.action({action={id="toggle"},silent=true})
    assert(search().items[1].state == false, "own toggle is independent of external assertions")
    s.timers.sleep({seconds=1.1})
    plugin.event({type="status.open"})
    assert(search().items[1].subtitle == nil)
    s.background(function() s.process.run({executable="/usr/bin/caffeinate",arguments={"-i","-t","1"}}) end)
    s.timers.sleep({seconds=0.2})
    plugin.event({type="status.open"})
    assert(search().items[1].subtitle == nil, "system-only sleep assertions do not count as display assertions")
    s.timers.sleep({seconds=1.1})
    return true
end
